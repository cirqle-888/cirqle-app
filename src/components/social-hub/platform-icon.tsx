/**
 * Platform brand marks. lucide-react v1 dropped brand icons (Facebook/Instagram),
 * so these are small inline SVGs used everywhere the Social Hub shows a
 * platform. Colour follows the brand by default; pass className to override.
 */

export function InstagramIcon({ className = 'w-4 h-4' }: { className?: string }) {
  return (
    <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" className={className} aria-hidden>
      <rect x="2" y="2" width="20" height="20" rx="5" ry="5" />
      <path d="M16 11.37A4 4 0 1 1 12.63 8 4 4 0 0 1 16 11.37z" />
      <line x1="17.5" y1="6.5" x2="17.51" y2="6.5" />
    </svg>
  )
}

export function FacebookIcon({ className = 'w-4 h-4' }: { className?: string }) {
  return (
    <svg viewBox="0 0 24 24" fill="currentColor" className={className} aria-hidden>
      <path d="M22 12a10 10 0 1 0-11.56 9.88v-6.99H7.9V12h2.54V9.8c0-2.5 1.49-3.89 3.78-3.89 1.09 0 2.24.2 2.24.2v2.46h-1.26c-1.24 0-1.63.77-1.63 1.56V12h2.78l-.44 2.89h-2.34v6.99A10 10 0 0 0 22 12z" />
    </svg>
  )
}

export function PlatformIcon({
  platform,
  className,
}: {
  platform: 'facebook_page' | 'instagram' | string
  className?: string
}) {
  if (platform === 'instagram') return <InstagramIcon className={className ?? 'w-4 h-4 text-pink-500'} />
  return <FacebookIcon className={className ?? 'w-4 h-4 text-blue-500'} />
}
